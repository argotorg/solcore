#!/usr/bin/env python3
"""Generate std/coerce.solc: the Coerce type class and the classic-Solidity
widening coercion instances over the full uintN / intN ladder.

Coverage (runtime, value-level implicit conversions of classic Solidity):
  * unsigned widening   uintN -> uintM   (M > N)   identity reinterpretation
  * signed widening     intN  -> intM    (M > N)   sign-extend from the source width
  * unsigned to signed  uintN -> intM    (M > N)   identity (positive value fits)

Not covered (not implicit in Solidity, or not runtime coercions): bytesN<->bytesM,
bytesN<->int, bool<->int, enum<->int, narrowing, intN->uintM, address payable,
and number/string literals (which already go through Int.fromInteger / Str.fromString).

Encoding: the Coerce class carries the target as a weak argument, but checkOverlap
keys only on the main type, so several targets per source would collide. The
instance head therefore carries both ends as Pair(src, Proxy(tgt)) : Coerce(tgt);
distinct (src, tgt) pairs never overlap and the fully concrete heads need no
condition pragmas.

Representation convention: value types are stored in a full 256-bit word with no
masking. uintN is zero-extended, intN is sign-extended. Widening to an unsigned or
wider-signed target is then a pure reinterpretation; widening a signed source uses
signextend so the result is correct even for a non-canonical source.
"""

import os

# Bit widths of the integer ladder: 8, 16, ..., 256.
WIDTHS = list(range(8, 257, 8))

HEADER = """// Generated by scripts/gen-std-coerce.py. Run the script to regenerate.
//
// The Coerce type class and the classic-Solidity widening coercions over the
// uintN / intN ladder. Covered (runtime, value-level implicit conversions):
//   * unsigned widening   uintN -> uintM   (M > N)   identity reinterpretation
//   * signed widening      intN -> intM    (M > N)   sign-extend from source width
//   * unsigned to signed   uintN -> intM   (M > N)   identity (positive value fits)
// Only the covering (single-hop) edges are written out; the coercion-closure pass
// (Solcore.Desugarer.CoercionClosure) synthesizes the rest of the ladder.
// Not covered (not implicit in Solidity, or not runtime coercions): bytesN<->bytesM,
// bytesN<->int, bool<->int, enum<->int, narrowing, intN->uintM, address payable,
// and number/string literals (handled by Int.fromInteger / Str.fromString).
//
// Encoding: the instance head carries both ends as Pair(src, Proxy(tgt)) : Coerce(tgt),
// so several targets per source do not collide under checkOverlap (which keys on the
// main type) and the fully concrete heads need no condition pragmas.
//
// Representation: value types are stored in a full 256-bit word with no masking;
// uintN is zero-extended and intN is sign-extended. Widening to an unsigned or a
// wider signed target is a pure reinterpretation; a signed source uses signextend.
//
// Only the covering (single-hop) edges uintN -> uint(N+8), intN -> int(N+8) and
// uintN -> int(N+8) are written out here. The compiler's coercion-closure desugar
// pass (Solcore.Desugarer.CoercionClosure) builds the coercion graph from these and
// synthesizes every reachable multi-hop coercion (e.g. uint8 -> uint256) as a
// composite Coerce instance, so the whole lattice closure is available downstream
// without being materialized in this file."""

# uint256 already exists in std/std.solc; every other width is new here.
NEW_UINT_WIDTHS = [w for w in WIDTHS if w != 256]
NEW_INT_WIDTHS = list(WIDTHS)


def typedef_block(name):
    return "\n".join(
        [
            f"data {name} = {name}(word);",
            f"instance {name} : Typedef(word) {{",
            f"    function abs(w : word) -> {name} {{ return {name}(w); }}",
            f"    function rep(x : {name}) -> word {{ match x {{ | {name}(w) => return w; }} }}",
            "}",
        ]
    )


def coerce_instance(src, tgt, witness):
    return "\n".join(
        [
            f"instance Pair({src}, Proxy({tgt})) : Coerce({tgt}) {{",
            f"    function coerce(p : Pair({src}, Proxy({tgt}))) -> {tgt} {{",
            f"        match p {{ | Pair(x, _) => return {witness}; }}",
            "    }",
            "}",
        ]
    )


def instances():
    ident = "Typedef.abs(Typedef.rep(x))"
    out = []
    # Only the covering (single-hop) edges of the widening lattice are emitted;
    # the compiler's coercion-closure desugar pass (Solcore.Desugarer.CoercionClosure)
    # composes every reachable multi-hop coercion from these via the coercion graph.
    #   * unsigned widening   uintN -> uint(N+8)   identity
    #   * signed widening      intN -> int(N+8)    sign-extend from the source byte
    #   * unsigned to signed   uintN -> int(N+8)   identity (positive value fits)
    for n in WIDTHS:
        m = n + 8
        if m not in WIDTHS:  # top of the ladder has no wider width
            continue
        byte = n // 8 - 1
        out.append(coerce_instance(f"uint{n}", f"uint{m}", ident))
        out.append(
            coerce_instance(
                f"int{n}",
                f"int{m}",
                f"Typedef.abs(signextend({byte}, Typedef.rep(x)))",
            )
        )
        out.append(coerce_instance(f"uint{n}", f"int{m}", ident))
    return out


def export_block():
    names = ["Coerce", "Pair(*)"]
    names += [f"uint{w}(*)" for w in NEW_UINT_WIDTHS]
    names += [f"int{w}(*)" for w in NEW_INT_WIDTHS]
    lines = ["export {"]
    for i, n in enumerate(names):
        sep = "," if i < len(names) - 1 else ""
        lines.append(f"    {n}{sep}")
    lines.append("};")
    return "\n".join(lines)


def render():
    parts = [
        HEADER,
        "",
        "import std.{*};",
        "import std.opcodes.{signextend};",
        "",
        export_block(),
        "",
        "data Pair(a, b) = Pair(a, b);",
        "",
        "forall self r . class self : Coerce(r) {",
        "    function coerce(x : self) -> r;",
        "}",
        "",
        "// --- integer ladder types (uint256 already defined in std) ---",
    ]
    for w in NEW_UINT_WIDTHS:
        parts.append("")
        parts.append(typedef_block(f"uint{w}"))
    for w in NEW_INT_WIDTHS:
        parts.append("")
        parts.append(typedef_block(f"int{w}"))
    parts.append("")
    parts.append("// --- widening coercion instances ---")
    for inst in instances():
        parts.append("")
        parts.append(inst)
    return "\n".join(parts) + "\n"


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(script_dir, os.pardir, "std", "coerce.solc")
    with open(out_path, "w") as f:
        f.write(render())
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
